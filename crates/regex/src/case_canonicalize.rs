/// Returns the case canonical version of the given string.
// port: CaseCanonicalize#caseCanonicalize(String)
pub fn case_canonicalize(s: &[u16]) -> Vec<u16> {
    let n = s.len();
    let mut i = 0;
    while i < n {
        let ch = s[i];
        let cu = case_canonicalize_char(ch);
        if cu != ch {
            let mut sb = s.to_vec();
            sb[i] = cu;
            i += 1;
            while i < n {
                sb[i] = case_canonicalize_char(s[i]);
                i += 1;
            }
            return sb;
        }
        i += 1;
    }
    s.to_vec()
}

/// Returns the case canonical version of the given code-unit. ECMAScript 5 explicitly says that
/// code-units are to be treated as their code-point equivalent, even surrogates.
// port: CaseCanonicalize#caseCanonicalize(char)
pub fn case_canonicalize_char(ch: u16) -> u16 {
    if ch < 0x80 {
        // Normal case.
        return if (b'A' as u16) <= ch && ch <= (b'Z' as u16) {
            ch | 32
        } else {
            ch
        };
    }
    // Non-ASCII case.
    if CASE_SENSITIVE.contains(ch as i32) {
        for ds in CANON_DELTA_SETS.iter() {
            if ds.code_units.contains(ch as i32) {
                return (ch as i32).wrapping_sub(ds.delta) as u16;
            }
        }
    }
    ch
}

/// Given a character range that may include case sensitive code-units, such as `[0-9B-M]`,
/// returns the character range that includes all the code-units in the input and those that are
/// case-insensitively equivalent to a code-unit in the input.
// port: CaseCanonicalize#expandToAllMatched
pub fn expand_to_all_matched(ranges: &CharRanges) -> CharRanges {
    let case_sensitive = ranges.intersection(&CASE_SENSITIVE);
    if case_sensitive.is_empty() {
        return ranges.clone();
    }
    let mut expanded = char_ranges::EMPTY.clone();
    for ds in DELTA_SETS.iter() {
        expanded = expanded.union(&case_sensitive.intersection(&ds.code_units).shift(-ds.delta));
    }
    ranges.union(&expanded)
}

static UCASE_ASCII_LETTERS: LazyLock<CharRanges> =
    LazyLock::new(|| CharRanges::inclusive(b'A' as i32, b'Z' as i32).unwrap());

/// Given a character range that may include case sensitive code-units, such as `[0-9B-M]`,
/// returns the character range that includes the minimal set of code units such that for every
/// code unit in the input there is a case-sensitively equivalent canonical code unit in the
/// output.
// port: CaseCanonicalize#reduceToMinimum
pub fn reduce_to_minimum(ranges: &CharRanges) -> CharRanges {
    let case_sensitive = ranges.intersection(&CASE_SENSITIVE);
    if case_sensitive.is_empty() {
        return ranges.clone();
    }
    let mut expanded = char_ranges::EMPTY.clone();
    for ds in CANON_DELTA_SETS.iter() {
        expanded = expanded.union(&case_sensitive.intersection(&ds.code_units).shift(-ds.delta));
    }
    // Letters a-z gzip better than uppercase A-Z since JavaScript keywords are lower-case, so,
    // even though the definition of Canonicalize is based on String.prototype.toUpperCase, we use
    // lowercase ASCII characters in the minimal form.
    expanded = expanded
        .difference(&UCASE_ASCII_LETTERS)
        .union(&expanded.intersection(&UCASE_ASCII_LETTERS).shift(32));
    ranges.difference(&case_sensitive).union(&expanded)
}

