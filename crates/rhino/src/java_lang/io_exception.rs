// Ported from OpenJDK 21 (the src.zip of Temurin-21.0.12.1+1): java.base/java/io/IOException.java,
//   java.base/java/lang/Throwable.java, java.base/sun/nio/fs/UnixException.java.

use std::{fmt, io};
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct IOException {
    message: String,
}
impl IOException {
    // port: IOException#IOException(String)
    pub fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }
    // port: Throwable#getMessage
    pub fn get_message(&self) -> &str {
        &self.message
    }
    // port: UnixException#translateToIOException
    pub fn from_io(error: io::Error, path: &str) -> Self {
        match error.kind() {
            io::ErrorKind::NotFound => Self::new(path),
            io::ErrorKind::PermissionDenied => Self::new(path),
            _ => Self::new(error.to_string()),
        }
    }
}
impl fmt::Display for IOException {
    // port: Throwable#toString
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.message)
    }
}
impl std::error::Error for IOException {}
