// port: Character#digit(char,int) (radix 10, JDK 21 BMP decimal digits)
pub fn digit_decimal(c: u16) -> i32 {
    const ZEROS: &[u16] = &[
        48, 1632, 1776, 1984, 2406, 2534, 2662, 2790, 2918, 3046, 3174, 3302, 3430, 3558, 3664,
        3792, 3872, 4160, 4240, 6112, 6160, 6470, 6608, 6784, 6800, 6992, 7088, 7232, 7248, 42528,
        43216, 43264, 43472, 43504, 43600, 44016, 65296,
    ];
    let i = ZEROS.partition_point(|&zero| zero <= c);
    if i > 0 && c - ZEROS[i - 1] < 10 {
        (c - ZEROS[i - 1]) as i32
    } else {
        -1
    }
}

