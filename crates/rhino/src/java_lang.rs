// port: CharacterData#of
fn character_flags(c: i32) -> u8 {
    let ranges = character_data::RANGES;
    let i = ranges.partition_point(|r| r.1 < c);
    if i < ranges.len() && ranges[i].0 <= c {
        ranges[i].2
    } else {
        0
    }
}
