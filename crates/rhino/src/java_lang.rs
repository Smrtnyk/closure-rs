struct DoubleToDecimal {
    bytes: Vec<u8>,
}
// JDK method names and mutable conversion buffer are retained.
#[allow(clippy::wrong_self_convention)]
impl DoubleToDecimal {
    const P: i32 = 53;
    const Q_MIN: i32 = -1074;
    const C_MIN: i64 = 1 << 52;
    const BQ_MASK: i32 = 2047;
    const T_MASK: i64 = (1 << 52) - 1;
    const C_TINY: i64 = 3;
    const MASK_63: i64 = i64::MAX;
    const MASK_28: i32 = (1 << 28) - 1;
    const H: i32 = 17;
    const NON_SPECIAL: i32 = 0;
    const PLUS_ZERO: i32 = 1;
    const MINUS_ZERO: i32 = 2;
    const PLUS_INF: i32 = 3;
    const MINUS_INF: i32 = 4;
    const NAN: i32 = 5;
    // port: DoubleToDecimal#DoubleToDecimal
    fn new() -> Self {
        Self {
            bytes: Vec::with_capacity(24),
        }
    }
    // port: DoubleToDecimal#toString
    fn to_string(v: f64) -> String {
        Self::new().to_decimal_string(v)
    }
    // port: DoubleToDecimal#toDecimalString
    fn to_decimal_string(&mut self, v: f64) -> String {
        match self.to_decimal(v) {
            Self::NON_SPECIAL => self.chars_to_string(),
            Self::PLUS_ZERO => "0.0".into(),
            Self::MINUS_ZERO => "-0.0".into(),
            Self::PLUS_INF => "Infinity".into(),
            Self::MINUS_INF => "-Infinity".into(),
            _ => "NaN".into(),
        }
    }
    // port: DoubleToDecimal#toDecimal(double, FormattedFPDecimal)
    fn to_decimal(&mut self, v: f64) -> i32 {
        let bits = v.to_bits() as i64;
        let t = bits & Self::T_MASK;
        let bq = ((bits as u64 >> (Self::P - 1)) as i32) & Self::BQ_MASK;
        if bq < Self::BQ_MASK {
            self.bytes.clear();
            if bits < 0 {
                self.append(b'-');
            }
            if bq != 0 {
                let mq = -Self::Q_MIN + 1 - bq;
                let c = Self::C_MIN | t;
                if 0 < mq && mq < Self::P {
                    let f = c >> mq;
                    if f << mq == c {
                        return self.to_chars(f, 0);
                    }
                }
                return self.to_decimal_parts(-mq, c, 0);
            }
            if t != 0 {
                return if t < Self::C_TINY {
                    self.to_decimal_parts(Self::Q_MIN, 10 * t, -1)
                } else {
                    self.to_decimal_parts(Self::Q_MIN, t, 0)
                };
            }
            return if bits == 0 {
                Self::PLUS_ZERO
            } else {
                Self::MINUS_ZERO
            };
        }
        if t != 0 {
            return Self::NAN;
        }
        if bits > 0 {
            Self::PLUS_INF
        } else {
            Self::MINUS_INF
        }
    }
    // port: DoubleToDecimal#toDecimal(int, long, int, FormattedFPDecimal)
    fn to_decimal_parts(&mut self, q: i32, c: i64, dk: i32) -> i32 {
        let out = c as i32 & 1;
        let cb = c << 2;
        let cbr = cb + 2;
        let (cbl, k) = if c != Self::C_MIN || q == Self::Q_MIN {
            (cb - 2, flog10pow2(q))
        } else {
            (cb - 1, flog10three_quarters_pow2(q))
        };
        let h = q + flog2pow10(-k) + 2;
        let g1 = g1(k);
        let g0 = g0(k);
        let vb = Self::rop(g1, g0, cb << h);
        let vbl = Self::rop(g1, g0, cbl << h);
        let vbr = Self::rop(g1, g0, cbr << h);
        let s = vb >> 2;
        if s >= 100 {
            let sp10 = 10 * multiply_high(s, 115_292_150_460_684_698 << 4);
            let tp10 = sp10 + 10;
            let upin = vbl + out as i64 <= sp10 << 2;
            let wpin = (tp10 << 2) + out as i64 <= vbr;
            if upin != wpin {
                return self.to_chars(if upin { sp10 } else { tp10 }, k);
            }
        }
        let t = s + 1;
        let uin = vbl + out as i64 <= s << 2;
        let win = (t << 2) + out as i64 <= vbr;
        if uin != win {
            return self.to_chars(if uin { s } else { t }, k + dk);
        }
        let cmp = vb - ((s + t) << 1);
        self.to_chars(
            if cmp < 0 || cmp == 0 && (s & 1) == 0 {
                s
            } else {
                t
            },
            k + dk,
        )
    }
    // port: DoubleToDecimal#rop
    fn rop(g1: i64, g0: i64, cp: i64) -> i64 {
        let x1 = multiply_high(g0, cp);
        let y0 = g1.wrapping_mul(cp);
        let y1 = multiply_high(g1, cp);
        let z = ((y0 as u64 >> 1) as i64).wrapping_add(x1);
        let vbp = y1 + (z as u64 >> 63) as i64;
        vbp | (((z & Self::MASK_63).wrapping_add(Self::MASK_63) as u64 >> 63) as i64)
    }
    // port: DoubleToDecimal#toChars
    fn to_chars(&mut self, mut f: i64, mut e: i32) -> i32 {
        let mut len = flog10pow2(64 - f.leading_zeros() as i32);
        if f >= pow10(len) {
            len += 1;
        }
        f *= pow10(Self::H - len);
        e += len;
        let hm = (multiply_high(f, 193_428_131_138_340_668) as u64 >> 20) as i64;
        let l = (f - 100_000_000 * hm) as i32;
        let h = ((hm * 1_441_151_881) >> 57) as i32;
        let m = (hm - 100_000_000 * h as i64) as i32;
        if 0 < e && e <= 7 {
            return self.to_chars1(h, m, l, e);
        }
        if -3 < e && e <= 0 {
            return self.to_chars2(h, m, l, e);
        }
        self.to_chars3(h, m, l, e)
    }
    // port: DoubleToDecimal#toChars1
    fn to_chars1(&mut self, h: i32, m: i32, l: i32, e: i32) -> i32 {
        self.append_digit(h);
        let mut y = Self::y(m);
        let mut i = 1;
        while i < e {
            let t = y.wrapping_mul(10);
            self.append_digit((t as u32 >> 28) as i32);
            y = t & Self::MASK_28;
            i += 1;
        }
        self.append(b'.');
        while i <= 8 {
            let t = y.wrapping_mul(10);
            self.append_digit((t as u32 >> 28) as i32);
            y = t & Self::MASK_28;
            i += 1;
        }
        self.low_digits(l);
        Self::NON_SPECIAL
    }
    // port: DoubleToDecimal#toChars2
    fn to_chars2(&mut self, h: i32, m: i32, l: i32, mut e: i32) -> i32 {
        self.append_digit(0);
        self.append(b'.');
        while e < 0 {
            self.append_digit(0);
            e += 1;
        }
        self.append_digit(h);
        self.append8_digits(m);
        self.low_digits(l);
        Self::NON_SPECIAL
    }
    // port: DoubleToDecimal#toChars3
    fn to_chars3(&mut self, h: i32, m: i32, l: i32, e: i32) -> i32 {
        self.append_digit(h);
        self.append(b'.');
        self.append8_digits(m);
        self.low_digits(l);
        self.exponent(e - 1);
        Self::NON_SPECIAL
    }
    // port: DoubleToDecimal#lowDigits
    fn low_digits(&mut self, l: i32) {
        if l != 0 {
            self.append8_digits(l);
        }
        self.remove_trailing_zeroes();
    }
    // port: DoubleToDecimal#append8Digits
    fn append8_digits(&mut self, m: i32) {
        let mut y = Self::y(m);
        for _ in 0..8 {
            let t = y.wrapping_mul(10);
            self.append_digit((t as u32 >> 28) as i32);
            y = t & Self::MASK_28;
        }
    }
    // port: DoubleToDecimal#removeTrailingZeroes
    fn remove_trailing_zeroes(&mut self) {
        while self.bytes.last() == Some(&b'0') {
            self.bytes.pop();
        }
        if self.bytes.last() == Some(&b'.') {
            self.bytes.push(b'0');
        }
    }
    // port: DoubleToDecimal#y
    fn y(a: i32) -> i32 {
        (multiply_high(((a + 1) as i64) << 28, 193_428_131_138_340_668) as u64 >> 20) as i32 - 1
    }
    // port: DoubleToDecimal#exponent
    fn exponent(&mut self, mut e: i32) {
        self.append(b'E');
        if e < 0 {
            self.append(b'-');
            e = -e;
        }
        if e < 10 {
            self.append_digit(e);
            return;
        }
        if e >= 100 {
            let d = (e * 1311) >> 17;
            self.append_digit(d);
            e -= 100 * d;
        }
        let d = (e * 103) >> 10;
        self.append_digit(d);
        self.append_digit(e - 10 * d);
    }
    // port: DoubleToDecimal#append
    fn append(&mut self, c: u8) {
        self.bytes.push(c);
    }
    // port: DoubleToDecimal#appendDigit
    fn append_digit(&mut self, d: i32) {
        self.bytes.push(b'0' + d as u8);
    }
    // port: DoubleToDecimal#charsToString
    fn chars_to_string(&self) -> String {
        String::from_utf8(self.bytes.clone()).unwrap()
    }
}
